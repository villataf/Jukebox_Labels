use serde::{Deserialize, Serialize};

/// L'ordine delle varianti è l'indice delle colonne nelle tabelle qui sotto: le nuove lingue vanno in fondo.
#[derive(Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Lang {
    #[default]
    It,
    En,
    De,
    Fr,
    Zh,
    Ja,
    Es,
}

impl Lang {
    /// L'ordine del menu.
    pub const ALL: [Lang; 7] = [Lang::It, Lang::En, Lang::Es, Lang::De, Lang::Fr, Lang::Zh, Lang::Ja];

    pub fn native_name(self) -> &'static str {
        match self {
            Lang::It => "Italiano",
            Lang::En => "English",
            Lang::Es => "Español",
            Lang::De => "Deutsch",
            Lang::Fr => "Français",
            Lang::Zh => "中文",
            Lang::Ja => "日本語",
        }
    }

    pub fn code(self) -> &'static str {
        ["it", "en", "de", "fr", "zh", "ja", "es"][self.i()]
    }

    fn i(self) -> usize {
        self as usize
    }

    /// La lingua del sistema, se è una di quelle tradotte.
    pub fn from_system() -> Lang {
        let v = ["LC_ALL", "LC_MESSAGES", "LANG"].iter().find_map(|k| std::env::var(k).ok()).unwrap_or_default();
        match v.get(..2).unwrap_or("") {
            "en" => Lang::En,
            "es" => Lang::Es,
            "de" => Lang::De,
            "fr" => Lang::Fr,
            "zh" => Lang::Zh,
            "ja" => Lang::Ja,
            _ => Lang::It,
        }
    }
}

